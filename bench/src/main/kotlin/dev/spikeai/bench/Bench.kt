package dev.spikeai.bench

import dev.spikeai.embed.ClipEncoder
import dev.spikeai.embed.ImagePrep
import dev.spikeai.search.FlatIndex
import dev.spikeai.search.Hnsw
import dev.spikeai.search.LinearProbe
import java.io.File
import javax.imageio.ImageIO
import kotlin.random.Random

/**
 * M1 benchmark on COCO (Karpathy test, first 1,000 photos × 5 human captions).
 * Task: type a caption → is the right photo in the top 1 / 5 / 10 of 1,000?
 */
fun main(args: Array<String>) {
    if (args.getOrNull(2) == "labels") return labelExperiment(File(args[0]))
    val work = File(args[0]); val results = File(args[1])
    val coco = File(work, "eval/coco1k"); val models = File(work, "models/mobileclip")
    val rows = File(coco, "captions.tsv").readLines().map { it.split('\t') }
    val names = rows.map { it[0] }
    val captions = rows.flatMapIndexed { img, r -> r.drop(1).map { img to it } }
    val tokenizerJson = File(models, "tokenizer.json").readText()
    val out = StringBuilder()
    fun log(s: String) { println(s); out.appendLine(s) }

    log("# M1 benchmark — MobileCLIP-S0 photo search\n")
    log("_COCO Karpathy test split, first ${names.size} photos, ${captions.size} captions. Laptop CPU (Apple M-series), ONNX Runtime 1.31.1, 4 threads. Generated by `./gradlew :bench:run`._\n")

    // Decode + preprocess once (our Kotlin resize), reuse for every model variant.
    val t0 = System.nanoTime()
    val pixels = names.map { n ->
        val img = ImageIO.read(File(coco, "png/${n.removeSuffix(".jpg")}.png")) // PIL-decoded, lossless
        val argb = img.getRGB(0, 0, img.width, img.height, null, 0, img.width)
        ImagePrep.toChw(ImagePrep.resizeShortSideAndCrop(argb, img.width, img.height))
    }
    val prepMs = (System.nanoTime() - t0) / 1e6 / names.size

    data class Variant(val label: String, val text: String, val vision: String)
    val variants = listOf(
        Variant("full size (fp32)", "text_model.onnx", "vision_model.onnx"),
        Variant("quantized (uint8, downloaded)", "text_model_uint8.onnx", "vision_model_uint8.onnx"),
        Variant("our int8 text + full-size images", "text_model_q8.onnx", "vision_model.onnx"),
    )
    val imageVecs = HashMap<String, List<FloatArray>>(); val textVecs = HashMap<String, List<FloatArray>>()
    log("## Search accuracy and speed\n")
    log("| Models | Size on disk | Image → vector | Text → vector | Found in top 1 | top 5 | top 10 |")
    log("|---|---|---|---|---|---|---|")
    for (v in variants) {
        ClipEncoder.load(File(models, v.text).path, File(models, v.vision).path, tokenizerJson).use { clip ->
            clip.embedImage(pixels[0]); clip.embedText("warm up")
            val a = System.nanoTime(); val iv = pixels.map(clip::embedImage); val imgMs = (System.nanoTime() - a) / 1e6 / pixels.size
            val b = System.nanoTime(); val tv = captions.map { clip.embedText(it.second) }; val txtMs = (System.nanoTime() - b) / 1e6 / captions.size
            imageVecs[v.label] = iv; textVecs[v.label] = tv
            val r = recall(iv, tv, captions.map { it.first })
            val mb = (File(models, v.text).length() + File(models, v.vision).length()) / 1_000_000
            log("| ${v.label} | $mb MB | %.1f ms | %.1f ms | %.1f%% | %.1f%% | %.1f%% |".format(imgMs, txtMs, r[0], r[1], r[2]))
        }
    }
    val mixed = recall(imageVecs.getValue("quantized (uint8, downloaded)"), textVecs.getValue("full size (fp32)"), captions.map { it.first })
    log("| downloaded uint8 images + full-size text | | | | %.1f%% | %.1f%% | %.1f%% |".format(mixed[0], mixed[1], mixed[2]))
    log("\nImage decode + resize + crop in Kotlin: %.1f ms per photo.\n".format(prepMs))

    // Our resize vs the official PIL preprocessing.
    val pil = File(coco, "pil_vectors.tsv").readLines().map { l -> l.split('\t').let { it[0] to it[1].split(' ').map(String::toFloat).toFloatArray() } }
    val fp = imageVecs.getValue("full size (fp32)")
    val sims = pil.map { (n, v) -> dot(fp[names.indexOf(n)], v) }
    log("Our Kotlin resize vs the official Python (PIL) preprocessing, ${sims.size} photos: same direction %.4f on average (worst %.4f; 1 = identical).\n".format(sims.average(), sims.min()))

    // HNSW vs brute force on the real photo vectors.
    log("## Index: HNSW vs checking every photo\n")
    val flat = FlatIndex(); fp.forEachIndexed { i, v -> flat.add(i, v) }
    val queries = textVecs.getValue("full size (fp32)")
    val truth = queries.map { q -> flat.search(q, 10).map { it.id }.toSet() }
    val tFlat = timePerQuery(queries) { flat.search(it, 10) }
    log("| Index | Matches brute-force top 10 | Time per search |")
    log("|---|---|---|")
    log("| check every photo | 100%% | %.3f ms |".format(tFlat))
    val hnsw = Hnsw(m = 16, efConstruction = 100); fp.forEachIndexed { i, v -> hnsw.add(i, v) }
    for (ef in listOf(16, 64, 200)) {
        hnsw.ef = ef
        val hit = queries.indices.sumOf { i -> hnsw.search(queries[i], 10).count { it.id in truth[i] } }
        log("| HNSW ef=$ef | %.1f%% | %.3f ms |".format(100.0 * hit / (queries.size * 10), timePerQuery(queries) { hnsw.search(it, 10) }))
    }
    log("\nWith only ${fp.size} photos, checking every one is already fast; HNSW pays off at tens of thousands.\n")

    // Personal labels: few-shot training vs plain text search.
    log("## Personal labels: learn a concept from a few tagged photos\n")
    log("A photo counts as a positive if at least 2 of its 5 captions mention the word. Score = average precision on the photos not used for training (1.0 = all positives ranked first). Mean of 5 random draws.\n")
    log("Each cell: text search only → after training on N tagged photos (same held-out photos for both).\n")
    log("| Concept | Positives | 1 tagged | 5 tagged | 10 tagged |")
    log("|---|---|---|---|---|")
    ClipEncoder.load(File(models, "text_model.onnx").path, File(models, "vision_model.onnx").path, tokenizerJson).use { clip ->
        val sums = Array(3) { DoubleArray(2) }; var count = 0
        for (word in listOf("dog", "pizza", "train", "giraffe", "surf", "kitchen", "bus", "snow", "cake", "laptop")) {
            val pos = rows.indices.filter { i -> rows[i].drop(1).count { Regex("\\b$word").containsMatchIn(it.lowercase()) } >= 2 }.toSet()
            if (pos.size < 15) continue
            val textVec = clip.embedText("a photo of a $word")
            val cells = listOf(1, 5, 10).mapIndexed { si, shots ->
                val pairs = (0 until 5).map { seed ->
                    val rnd = Random(seed)
                    val train = pos.shuffled(rnd).take(shots).toSet()
                    val negs = fp.indices.filter { it !in pos }.shuffled(rnd).take(50).toSet()
                    val probe = LinearProbe(512, init = textVec).apply { train(train.map { fp[it] }, negs.map { fp[it] }) }
                    val test = fp.indices.filter { it !in train && it !in negs }
                    ap(test, pos) { dot(fp[it], textVec) } to ap(test, pos) { probe.probability(fp[it]) }
                }
                val a = pairs.map { it.first }.average(); val b = pairs.map { it.second }.average()
                sums[si][0] += a; sums[si][1] += b
                "%.2f → %.2f".format(a, b)
            }
            count++
            log("| $word | ${pos.size} | " + cells.joinToString(" | ") + " |")
        }
        log("| **average** | | " + sums.joinToString(" | ") { "**%.3f → %.3f**".format(it[0] / count, it[1] / count) } + " |")
    }
    log("\nOn generic concepts text search is already strong; training helps from ~5 tagged photos. The real use is personal concepts text can't name (\"my dog\", \"my desk\"), which COCO can't measure.")
    results.mkdirs(); File(results, "m1-benchmark.md").writeText(out.toString())
    println("\nwrote ${File(results, "m1-benchmark.md")}")
}

private fun dot(a: FloatArray, b: FloatArray): Float { var s = 0f; for (i in a.indices) s += a[i] * b[i]; return s }

/** % of captions whose own photo is in the top 1 / 5 / 10. */
private fun recall(images: List<FloatArray>, texts: List<FloatArray>, owner: List<Int>): DoubleArray {
    val hits = IntArray(3)
    texts.forEachIndexed { t, q ->
        val mine = dot(q, images[owner[t]])
        val rank = images.count { dot(q, it) > mine } // how many photos beat the right one
        if (rank < 1) hits[0]++; if (rank < 5) hits[1]++; if (rank < 10) hits[2]++
    }
    return DoubleArray(3) { 100.0 * hits[it] / texts.size }
}

/** Average precision: walk down the ranking, average the precision at each positive. */
private fun ap(items: List<Int>, positives: Set<Int>, score: (Int) -> Float): Double {
    val ranked = items.sortedByDescending(score)
    var found = 0; var sum = 0.0
    ranked.forEachIndexed { i, id -> if (id in positives) { found++; sum += found / (i + 1.0) } }
    return if (found == 0) 0.0 else sum / found
}

private fun timePerQuery(qs: List<FloatArray>, f: (FloatArray) -> Unit): Double {
    qs.take(200).forEach(f)
    val t = System.nanoTime(); qs.forEach(f); return (System.nanoTime() - t) / 1e6 / qs.size
}

/** Try several few-shot methods on cached vectors; pick the one that beats plain text search. */
private fun labelExperiment(work: File) {
    val coco = File(work, "eval/coco1k"); val models = File(work, "models/mobileclip")
    val rows = File(coco, "captions.tsv").readLines().map { it.split('\t') }
    val cache = File(coco, "image_vectors_fp32.bin")
    ClipEncoder.load(File(models, "text_model.onnx").path, File(models, "vision_model.onnx").path, File(models, "tokenizer.json").readText()).use { clip ->
        val fp: List<FloatArray> = if (cache.exists()) cache.readBytes().let { b -> val bb = java.nio.ByteBuffer.wrap(b); List(rows.size) { FloatArray(512) { bb.float } } } else {
            val v = rows.map { r -> val img = ImageIO.read(File(coco, "png/${r[0].removeSuffix(".jpg")}.png")); clip.embedImage(ImagePrep.toChw(ImagePrep.resizeShortSideAndCrop(img.getRGB(0, 0, img.width, img.height, null, 0, img.width), img.width, img.height))) }
            val bb = java.nio.ByteBuffer.allocate(v.size * 512 * 4); v.forEach { a -> a.forEach { bb.putFloat(it) } }; cache.writeBytes(bb.array()); v
        }
        data class M(val name: String, val score: (FloatArray, List<FloatArray>, List<FloatArray>) -> (FloatArray) -> Float)
        val methods = listOf(
            M("text only") { t, _, _ -> { x -> dot(x, t) } },
            M("blend text + mean of tagged, λ=0.5") { t, p, _ -> val c = mean(p); { x -> dot(x, t) + 0.5f * dot(x, c) } },
            M("blend λ=0.25") { t, p, _ -> val c = mean(p); { x -> dot(x, t) + 0.25f * dot(x, c) } },
            M("blend λ=1") { t, p, _ -> val c = mean(p); { x -> dot(x, t) + 1f * dot(x, c) } },
            M("probe anchored l2=0.1 lr=0.01 e=30") { t, p, n -> val pr = LinearProbe(512, t).apply { train(p, n, epochs = 30, lr = 0.01f, l2 = 0.1f) }; { x -> pr.probability(x) } },
            M("probe anchored l2=1 lr=0.01 e=30") { t, p, n -> val pr = LinearProbe(512, t).apply { train(p, n, epochs = 30, lr = 0.01f, l2 = 1f) }; { x -> pr.probability(x) } },
            M("probe anchored l2=1 lr=0.003 e=30") { t, p, n -> val pr = LinearProbe(512, t).apply { train(p, n, epochs = 30, lr = 0.003f, l2 = 1f) }; { x -> pr.probability(x) } },
        )
        val words = listOf("dog", "pizza", "train", "giraffe", "kitchen", "bus", "snow", "cake", "laptop")
        for (m in methods) {
            val res = listOf(1, 5, 10).map { shots ->
                words.map { word ->
                    val pos = rows.indices.filter { i -> rows[i].drop(1).count { Regex("\\b$word").containsMatchIn(it.lowercase()) } >= 2 }.toSet()
                    val t = clip.embedText("a photo of a $word")
                    (0 until 5).map { seed ->
                        val rnd = Random(seed)
                        val tr = pos.shuffled(rnd).take(shots).toSet(); val ng = fp.indices.filter { it !in pos }.shuffled(rnd).take(50).toSet()
                        val f = m.score(t, tr.map { fp[it] }, ng.map { fp[it] })
                        ap(fp.indices.filter { it !in tr && it !in ng }, pos) { f(fp[it]) }
                    }.average()
                }.average()
            }
            println("%-40s 1: %.3f  5: %.3f  10: %.3f".format(m.name, res[0], res[1], res[2]))
        }
    }
}

private fun mean(vs: List<FloatArray>): FloatArray { val o = FloatArray(512); vs.forEach { v -> for (i in o.indices) o[i] += v[i] / vs.size }; return o }
